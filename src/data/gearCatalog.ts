export function getGearById(id: string): GearDefinition | undefined {
  if (id === 'mic_at2020') {
    return GEAR_CATALOG.find((g) => g.id === 'mic_at2035') || GEAR_CATALOG.find((g) => g.id === id);
  }
  if (id === 'inst_vocals') {
    return GEAR_CATALOG.find((g) => g.id === 'inst_voice');
  }
  if (id === 'inst_cymbals') {
    return GEAR_CATALOG.find((g) => g.id === 'inst_drum_cymbals');
  }
  if (id === 'inst_grand_piano') {
    return GEAR_CATALOG.find((g) => g.id === 'inst_acoustic_piano');
  }
  return GEAR_CATALOG.find((g) => g.id === id);
}
